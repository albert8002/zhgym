<div class="merke"><b>Merke:</b> Es zählt nur, was im Text steht, nicht dein Wissen und nicht, was wahrscheinlich ist. Falsch heisst: Der Text sagt das Gegenteil. Keine Angabe heisst: Der Text sagt dazu nichts.</div>
